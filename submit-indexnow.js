// Notifies Bing (and any other IndexNow-participating search engine) whenever
// a page listed in either of 4Guys' two sitemaps is new, changed, or has
// dropped out of the list (e.g. a vehicle sold and its page removed).
//
// Why this exists: 4Guys has two separate sitemaps, because Squarespace's own
// sitemap generator excludes anything rendered inside a code/embed block
// (which is how the AutoPlay VDP widget renders each vehicle page):
//   1. https://www.4guys.co.nz/sitemap.xml   - Squarespace's native sitemap,
//      covers the site's regular pages.
//   2. sitemap.xml in this repo (published at sitemap.4guys.co.nz/sitemap.xml)
//      - covers the ~280 vehicle-details pages Squarespace's sitemap misses.
// Rather than wait for Bing to re-crawl either sitemap on its own schedule,
// this script diffs both against their last known state and pushes just the
// changes straight to IndexNow's API, so new/changed/removed pages get
// noticed within minutes instead of days.
//
// The IndexNow key below is not a secret - it's a public ownership proof
// that's already hosted at the keyLocation URL for any search engine to read,
// so there's no need to store it as a GitHub secret.
//
// Run with: node submit-indexnow.js
// Expects sitemap.xml (the vehicle sitemap) to already exist in this repo's
// root, i.e. run this after crawl-sitemap.js in the same job.

const fs = require('fs');

const INDEXNOW_KEY = '9afb41a77277462a819f274bcdd578ab';
const KEY_LOCATION = 'https://www.4guys.co.nz/9afb41a77277462a819f274bcdd578ab.txt';
const HOST = 'www.4guys.co.nz';
const INDEXNOW_ENDPOINT = 'https://api.indexnow.org/indexnow';

const SQUARESPACE_SITEMAP_URL = 'https://www.4guys.co.nz/sitemap.xml';
const VEHICLE_SITEMAP_FILE = 'sitemap.xml'; // generated by crawl-sitemap.js, same repo root
const SNAPSHOT_FILE = 'indexnow-snapshot.json';
const MAX_URLS_PER_SUBMISSION = 10000; // IndexNow's documented per-request cap

// Pulls {loc, lastmod} pairs out of a sitemap.xml string without adding an XML
// parser dependency - both sitemaps here are simple, flat <url> lists.
function parseSitemap(xml) {
  const urls = new Map();
  const urlBlocks = xml.match(/<url>[\s\S]*?<\/url>/g) || [];
  for (const block of urlBlocks) {
    const locMatch = block.match(/<loc>(.*?)<\/loc>/);
    if (!locMatch) continue;
    const lastmodMatch = block.match(/<lastmod>(.*?)<\/lastmod>/);
    urls.set(locMatch[1].trim(), lastmodMatch ? lastmodMatch[1].trim() : '');
  }
  return urls;
}

function loadSnapshot() {
  try {
    return JSON.parse(fs.readFileSync(SNAPSHOT_FILE, 'utf8'));
  } catch (err) {
    return {}; // first run, or file doesn't exist yet - treat everything as new
  }
}

async function fetchSquarespaceSitemap() {
  const res = await fetch(SQUARESPACE_SITEMAP_URL);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${SQUARESPACE_SITEMAP_URL}: HTTP ${res.status}`);
  }
  return parseSitemap(await res.text());
}

function readVehicleSitemap() {
  const xml = fs.readFileSync(VEHICLE_SITEMAP_FILE, 'utf8');
  return parseSitemap(xml);
}

async function submitToIndexNow(urlList) {
  const chunks = [];
  for (let i = 0; i < urlList.length; i += MAX_URLS_PER_SUBMISSION) {
    chunks.push(urlList.slice(i, i + MAX_URLS_PER_SUBMISSION));
  }

  for (const chunk of chunks) {
    const res = await fetch(INDEXNOW_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json; charset=utf-8' },
      body: JSON.stringify({
        host: HOST,
        key: INDEXNOW_KEY,
        keyLocation: KEY_LOCATION,
        urlList: chunk,
      }),
    });
    // IndexNow returns 200 (or 202) on success, 403 if the key doesn't check
    // out, 422 if a URL doesn't belong to `host`, 429 if we're submitting too
    // fast. Surface anything unexpected rather than failing silently.
    if (res.status !== 200 && res.status !== 202) {
      throw new Error(`IndexNow submission failed: HTTP ${res.status} for ${chunk.length} URL(s)`);
    }
    console.log(`Submitted ${chunk.length} URL(s) to IndexNow - HTTP ${res.status}`);
  }
}

(async () => {
  console.log('Fetching current state of both sitemaps...');
  const [squarespaceUrls, vehicleUrls] = await Promise.all([
    fetchSquarespaceSitemap(),
    Promise.resolve(readVehicleSitemap()),
  ]);

  const current = new Map([...squarespaceUrls, ...vehicleUrls]);
  console.log(
    `Squarespace sitemap: ${squarespaceUrls.size} URL(s). Vehicle sitemap: ${vehicleUrls.size} URL(s). Combined: ${current.size} URL(s).`
  );

  const previous = loadSnapshot();
  const previousUrls = new Set(Object.keys(previous));

  const changed = [];
  for (const [url, lastmod] of current) {
    if (!previousUrls.has(url) || previous[url] !== lastmod) {
      changed.push(url);
    }
  }

  // URLs that were in the last snapshot but have now disappeared entirely
  // (e.g. a sold vehicle's page came down) - submitting these tells search
  // engines to go re-check the URL, which is how they discover it 404s and
  // should be dropped from the index, instead of waiting on a routine crawl.
  const removed = [...previousUrls].filter((url) => !current.has(url));

  const toSubmit = [...changed, ...removed];

  if (toSubmit.length === 0) {
    console.log('No new, changed, or removed URLs since the last run - nothing to submit.');
  } else {
    console.log(
      `${changed.length} new/changed URL(s), ${removed.length} removed URL(s) - submitting ${toSubmit.length} total.`
    );
    await submitToIndexNow(toSubmit);
  }

  // Snapshot only what's currently live - a removed URL is submitted once
  // (above) and then drops out of the snapshot rather than being resubmitted
  // on every future run.
  const nextSnapshot = Object.fromEntries(current);
  fs.writeFileSync(SNAPSHOT_FILE, JSON.stringify(nextSnapshot, null, 2) + '\n');
  console.log(`Wrote ${SNAPSHOT_FILE} with ${current.size} URL(s).`);
})().catch((err) => {
  console.error('IndexNow submission step failed:', err.message);
  process.exit(1);
});
